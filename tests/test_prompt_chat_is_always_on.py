"""'얘기하자'는 못 하는 놀이가 아니다 — 봇이 늘 하고 있는 일이다.

🔴 2026-08-31 젯슨 실기 턴3:
     [아이] 우리 오늘은 좀 자유 대화를 하면서 놀까?
     [티드] 자유 대화는 아직 못 해! 동물 소리 놀이 할까?
   그 세션의 1·2·9·10턴이 전부 자유대화였다 — **하고 있는 걸 못 한다고 했다.**
   원인은 바로 위의 규칙이다("색칠 놀이, 사물 찾기, 감정 놀이는 아직 못 한다").
   모델이 그 꼴을 **처음 듣는 낱말에 그대로 확장**해 '자유 대화'를 없는 놀이로 읽었다.

🔴 재현 조건이 중요하다 — **대화 이력이 있어야 난다.**
   이력을 비우고 물으면 0/6 으로 멀쩡하다. 직전에 봇이 "동물 소리 놀이 할까?" 하고
   권한 맥락에서만 5/5 로 터진다. 다음에 이걸 다시 잴 사람은 이력을 깔고 잴 것.
   (하마터면 '재현 안 됨'으로 닫을 뻔했다.)

여기서 지키는 것은 규칙 문구가 사라지지 않는 것뿐이다. 실제 응답은 API 를 타야
알 수 있어 오프라인 시험으로는 못 잡는다 — 그 측정은 위 실측 기록으로 남긴다.
"""
from app.config import settings


def test_the_prompt_says_talking_is_not_one_of_the_games():
    system = settings.prompts["system"]

    assert "놀이가 아니라" in system and "얘기하자" in system, \
        "'그냥 이야기하는 것은 놀이가 아니다'라는 규칙이 사라졌다"


def test_the_prompt_still_refuses_the_games_it_really_cannot_do():
    """얘기를 열어 준다고 색칠·사물찾기까지 열리면 없는 놀이를 광고하게 된다.

    2026-08-07 에 그 사고가 있었다 — 프롬프트가 없는 놀이를 광고해 날조가 났다.
    """
    system = settings.prompts["system"]

    for game in ["색칠", "사물 찾기", "감정 놀이"]:
        assert game in system, f"'{game}'을 못 한다는 규칙이 사라졌다"
    assert "그건 아직 못 해" in system
